/** shootCompose with a stand-in for Gradle: it records the run and answers with what the harness would have written. */
function fakeRun(answer: (run: HarnessRun) => Partial<HarnessResult>) {
  const runs: HarnessRun[] = [];
  const run = async (r: HarnessRun): Promise<HarnessResult> => {
    runs.push(r);
    return { code: 0, timedOut: false, output: "", result: null, ...answer(r) };
  };
  return { runs, run };
}

const options = (root: string, over: Partial<NativeShotOptions> = {}): NativeShotOptions => ({
  root,
  app: { path: "app", stack: "compose", source: "detected" },
  routes: ["/"],
  screens: [],
  outDir: join(root, "design", "shots"),
  viewports: [NATIVE_VIEWPORTS[1]!, NATIVE_VIEWPORTS[3]!],
  variants: [],
  states: [],
  audit: false,
  timeoutMs: 700_000,
  ...over,
});

const base = (root: string, run: ComposeShotDeps["run"], over: Partial<ComposeShotDeps> = {}): ComposeShotDeps => ({
  jdk: { java: "/jdk/bin/java", javaHome: "/jdk" },
  sdk: "/sdk",
  home: join(root, ".motif-home"),
  // Robolectric's Android libraries are already downloaded, unless a test says otherwise.
  robolectricCache: root,
  fetch: async () => new Response("", { status: 400 }),
  run,
  ...over,
});

