/** A machine with JDK 17 at JAVA_HOME and an Android SDK at ANDROID_HOME, or without either. */
function machine(opts: { jdk?: boolean; sdk?: boolean } = {}): DoctorDeps {
  const jdk = opts.jdk !== false;
  const sdk = opts.sdk !== false;
  return {
    platform: "linux",
    arch: "x64",
    home: "/home/dev",
    findBrowser: () => null,
    which: () => null,
    vars: { ...(jdk ? { JAVA_HOME: "/jdk" } : {}), ...(sdk ? { ANDROID_HOME: "/sdk" } : {}) },
    files: { exists: (p) => (jdk && p === "/jdk/bin/java") || (sdk && p === "/sdk"), read: () => null, list: () => [] },
    run: (cmd) =>
      jdk && cmd[0] === "/jdk/bin/java"
        ? { code: 0, stdout: "", stderr: `${cmd.includes("-XshowSettings:properties") ? "    java.home = /jdk\n" : ""}openjdk version "17.0.12" 2024-07-16\n` }
        : { code: 127, stdout: "" },
  };
}

const ctx = (flags: Record<string, string | string[] | boolean> = {}) => ({ positionals: [], flags });

/** Stand-ins for the screenshot run; the browser and the dev server must never be used. */
function fakes(answer?: (o: NativeShotOptions) => { routes: RouteResult[]; notes?: string[] }, doctor: DoctorDeps = machine()) {
  const calls: NativeShotOptions[] = [];
  const never = () => {
    throw new Error("a Compose app needs no browser or dev server");
  };
  const deps: ShotDeps = {
    findBrowser: never,
    devCommand: never,
    startDevServer: never,
    serveStatic: never,
    capture: never,
    compare: async () => [],
    today: () => "2026-10-20",
    which: () => null,
    doctor: () => doctor,
    shoot: async (o) => {
      calls.push(o);
      const made: { routes: RouteResult[]; notes?: string[] } = answer?.(o) ?? {
        routes: [...o.routes, ...o.screens].map((route) => ({ route, url: route, status: 200, shots: [join(o.outDir, `${route === "/" ? "index" : route.replace(/\W/g, "")}.mobile.png`)] })),
      };
      for (const shot of made.routes.flatMap((r) => r.shots)) {
        mkdirSync(dirname(shot), { recursive: true });
        if (!existsSync(shot)) writeFileSync(shot, "png");
      }
      return { routes: made.routes, issues: [], notes: made.notes ?? [] };
    },
  };
  return { deps, calls };
}

