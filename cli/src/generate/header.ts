import { stripBom } from "../text";

export const CSS_HEADER = '/* Generated by Motif — edit design/tokens.json instead, then run "motif tokens". */';
export const TS_HEADER = '// Generated by Motif — edit design/tokens.json instead, then run "motif tokens".';
/** The first line of a generated Android XML resource (an XML comment, so no declaration comes before it). */
export const XML_HEADER = '<!-- Generated by Motif — edit design/tokens.json instead, then run "motif tokens". -->';
export const JSON_COMMENT = 'Generated by Motif — edit design/tokens.json instead, then run "motif tokens".';

export interface GeneratedFile {
  /** Relative path with forward slashes. */
  path: string;
  content: string;
}

/** True only for files Motif wrote: they start with one of Motif's headers (or carry its $comment, for JSON). */
export function isMotifGenerated(path: string, text: string): boolean {
  const t = stripBom(text);
  if (path.endsWith(".json")) {
    try {
      return JSON.parse(t)?.$comment === JSON_COMMENT;
    } catch {
      return false;
    }
  }
  const first = t.split(/\r?\n/, 1)[0];
  return first === CSS_HEADER || first === TS_HEADER || first === XML_HEADER;
}

const normalize = (s: string) => stripBom(s).replace(/\r\n/g, "\n");

export function sameContent(a: string, b: string): boolean {
  return normalize(a) === normalize(b);
}
